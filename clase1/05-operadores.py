numero1 = 20
numero2 = 6

# Aca voy a escribir los operadores

print("Operadores matematicos")

print("Suma")
print(numero1 + numero2) # 26

print("Resta")
print(numero1 - numero2) # 14

print("Multiplicacion")
print(numero1 * numero2) # 120

print("Division")
print(numero1 / numero2) # 3.33

print("Division entera")
print(numero1 // numero2) # 3

print("Modulo o resto de la division")
print(numero1 % numero2) # 2

print("Potencia")
print(numero1 ** numero2) # 64000000