# Operadores Logicos
# AND OR NOT

# AND
print("AND")
# AND devuelve TRUE cuando las dos declaraciones/condiciones son verdaderas

print(9 > 2) # True
print(9 > 2 and 2 < 3) # True
print("------------")

# Tabla de verdad de AND
print(True and True) # True
print(True and False) # False
print(False and True) # False
print(False and False) # False

# OR
# Devuelve verdadero cuando cualquiera de las dos condiciones es verdadera
print(True or True) # True
print(True or False) # True
print(False or True) # True
print(False or False) # False

# NOT
# Invierte el estado de veracidad de algo
print(not True) # False
print(not False) # True